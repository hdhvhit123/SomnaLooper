#!/usr/bin/env python3
"""Generates app/src/main/res/values*/strings.xml from the tools/i18n/*.txt sources.
Format: `key|text` per line; plurals: `@key|one=..|other=..`."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, '..', '..', 'app', 'src', 'main', 'res')
DIRS = {'en': 'values', 'vi': 'values-vi', 'es': 'values-es', 'fr': 'values-fr', 'de': 'values-de',
        'pt-BR': 'values-pt-rBR', 'ru': 'values-ru', 'ja': 'values-ja', 'ko': 'values-ko',
        'zh-CN': 'values-zh-rCN', 'id': 'values-in', 'th': 'values-th'}
PH = re.compile(r'%\d\$[-#+ 0,(]*\d*(?:\.\d+)?[a-zA-Z]|%%')

def esc(s):
    s = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    s = s.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    if s.startswith('@') or s.startswith('?'):
        s = '\\' + s
    return s

def load(lang):
    strings, plurals = {}, {}
    for n, line in enumerate(open(os.path.join(HERE, lang + '.txt'), encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip():
            continue
        key, _, val = line.partition('|')
        if key.startswith('@'):
            plurals[key[1:]] = dict(p.split('=', 1) for p in val.split('|'))
        else:
            if key in strings: sys.exit(f'{lang}:{n} duplicate {key}')
            strings[key] = val
    return strings, plurals

base_s, base_p = load('en')
ok = True
for lang, d in DIRS.items():
    s, p = load(lang)
    missing = set(base_s) - set(s); extra = set(s) - set(base_s)
    if missing or extra:
        print(lang, 'missing', sorted(missing), 'extra', sorted(extra)); ok = False
    for k, v in s.items():
        if k in base_s and sorted(PH.findall(v)) != sorted(PH.findall(base_s[k])):
            print(f'{lang}: placeholder mismatch in {k}: {v}'); ok = False
    if set(p) != set(base_p):
        print(lang, 'plural keys differ'); ok = False
    for k, forms in p.items():
        if 'other' not in forms: print(lang, k, 'no other'); ok = False
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/i18n/gen.py. Edit the .txt sources instead. -->', '<resources>']
    for k in base_s:
        if k in s:
            attr = ' translatable="false"' if k == 'app_name' and lang == 'en' else ''
            if k == 'app_name' and lang != 'en': continue
            out.append(f'    <string name="{k}"{attr}>{esc(s[k])}</string>')
    for k in base_p:
        if k in p:
            out.append(f'    <plurals name="{k}">')
            for q in ['zero', 'one', 'two', 'few', 'many', 'other']:
                if q in p[k]: out.append(f'        <item quantity="{q}">{esc(p[k][q])}</item>')
            out.append('    </plurals>')
    out.append('</resources>\n')
    os.makedirs(os.path.join(RES, d), exist_ok=True)
    open(os.path.join(RES, d, 'strings.xml'), 'w', encoding='utf-8').write('\n'.join(out))
print('OK' if ok else 'ERRORS'); sys.exit(0 if ok else 1)
